"""Emit the tables and golden vectors the C++ modem needs.

Two implementations can only talk to each other if they share the *same* air
interface down to the bit: the same LDPC parity-check matrices, the same
interleaver permutation, the same preamble and pilot signs.  Those are built in
Python with numpy's PCG64, and re-deriving numpy's generator in C++ would be a
great way to introduce a silent, intermittent incompatibility.

So they are shipped as data instead.  A preamble is a constant of the air
interface in any case -- both stations must use the identical sequence -- and a
parity-check matrix is a table, not an algorithm.  What the C++ side implements
is the *work*: FFT, equalisation, QAM, belief propagation, framing.

Writes:

    cpp/data/wide.bin            float32 complex + int32 tables
    cpp/include/halcyon_tables.hpp   offsets, sizes and the rung table
    cpp/data/vec/*.f32          golden waveforms from the Python transmitter

Run with ``PYTHONPATH=.`` from the project root.
"""

from __future__ import annotations

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from halcyon.frame import block_sizes, table_for  # noqa: E402
from halcyon.modem import Modem  # noqa: E402
from halcyon.ofdm import Phy  # noqa: E402

DATA = os.path.join(ROOT, "cpp", "data")
VEC = os.path.join(DATA, "vec")
INCLUDE = os.path.join(ROOT, "cpp", "include")
MAX_BLOCKS = 12


class Blob:
    def __init__(self) -> None:
        self.buf = bytearray()

    def put(self, arr, dtype: str) -> tuple[int, int]:
        """Append an array; return (byte offset, element count)."""
        a = np.ascontiguousarray(arr).astype(dtype)
        off = len(self.buf)
        self.buf.extend(a.tobytes())
        return off, int(a.size)


def code_edges(code) -> np.ndarray:
    """(row, col) pairs of H, int32, row-major by row."""
    rows, cols = np.nonzero(code.H)
    return np.stack([rows, cols], axis=1).astype("<i4").ravel()


def emit_header(blob: Blob, info: dict) -> None:
    lines = [
        "// Generated by tools/dump_cpp_data.py -- do not edit by hand.",
        "//",
        "// Offsets point into cpp/data/wide.bin.  The tables are the air",
        "// interface: the C++ modem and the Python modem must share them",
        "// exactly, so they are data rather than two separate derivations.",
        "#pragma once",
        "#include <cstddef>",
        "",
        "namespace halcyon {",
        "",
        f"constexpr int kFs = {info['fs']};",
        f"constexpr int kFft = {info['n_fft']};",
        f"constexpr int kCp = {info['cp']};",
        f"constexpr int kBinLo = {info['bin_lo']};",
        f"constexpr int kBinHi = {info['bin_hi']};",
        f"constexpr int kPilotStep = {info['pilot_step']};",
        f"constexpr int kPreambleSyms = {info['preamble_syms']};",
        f"constexpr int kHeaderSyms = {info['header_syms']};",
        f"constexpr int kSymsPerBlock = {info['syms_per_block']};",
        f"constexpr int kSymLen = {info['sym_len']};",
        f"constexpr int kDataCarriers = {info['n_data']};",
        f"constexpr int kPilots = {info['n_pilots']};",
        f"constexpr int kHeaderN = {info['header_n']};",
        f"constexpr int kHeaderK = {info['header_k']};",
        f"constexpr std::size_t kPreambleOff = {info['preamble_off']};",
        f"constexpr int kPreambleSamples = {info['preamble_len']};",
        f"constexpr std::size_t kPilotOff = {info['pilot_off']};",
        f"constexpr std::size_t kHeaderEdgeOff = {info['header_edge_off']};",
        f"constexpr int kHeaderEdges = {info['header_edges']};",
        f"constexpr int kMaxBlocks = {MAX_BLOCKS};",
        "",
        "struct Rung {",
        "  const char* name;",
        "  int index;",
        "  int bps;",
        "  int rep;",
        "  int block_mult;",
        "  int uncoded;",
        "  int n;   // transmitted bits per block, including repetition",
        "  int k;   // information bits per block, CRC-16 inside",
        "  std::size_t edge_off;  // (row, col) pairs of the parity-check matrix",
        "  int edges;             // pair count",
        "  std::size_t perm_off[13];  // interleaver for blocks = 1..12",
        "};",
        "",
        f"constexpr int kRungCount = {len(info['rungs'])};",
        "const Rung kRungTable[] = {",
    ]
    for r in info["rungs"]:
        perms = ", ".join(str(p) for p in r["perm_off"])
        lines.append(
            f'    {{"{r["name"]}", {r["index"]}, {r["bps"]}, {r["rep"]}, '
            f'{r["block_mult"]}, {r["uncoded"]}, {r["n"]}, {r["k"]}, '
            f'{r["edge_off"]}, {r["edges"]}, {{{perms}}}}},'
        )
    lines += ["};", "", "}  // namespace halcyon", ""]
    path = os.path.join(INCLUDE, "halcyon_tables.hpp")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {path}")


def main() -> None:
    os.makedirs(DATA, exist_ok=True)
    os.makedirs(VEC, exist_ok=True)
    os.makedirs(INCLUDE, exist_ok=True)

    phy = Phy()
    modem = Modem(phy)
    blob = Blob()

    pre_off, pre_len = blob.put(np.asarray(phy.preamble, np.complex64), "<c8")
    pilot_off, _ = blob.put(np.asarray(phy.pilot_syms, np.complex64), "<c8")
    hdr_edge_off, hdr_edges = blob.put(code_edges(modem.header_code()), "<i4")

    rungs = []
    seen_codes: dict[tuple[int, int], tuple[int, int]] = {}
    for i in range(len(table_for(phy))):
        n, k = block_sizes(phy, i)
        m = table_for(phy)[i]
        code = modem.block_code(i)
        if code is None:
            edge_off, edges = hdr_edge_off, 0
        else:
            key = (code.n, code.k)
            if key in seen_codes:
                edge_off, edges = seen_codes[key]
            else:
                edge_off, edges = blob.put(code_edges(code), "<i4")
                seen_codes[key] = (edge_off, edges)
        # Entry 0 is unused: the C++ side indexes this by `blocks`, so entry b
        # is the interleaver for b blocks.  Emitting 12 entries instead of 13
        # shifted every rung by one, which wrote past the LLR buffer for a
        # single-block frame -- found with AddressSanitizer.
        perms = [0]
        for blocks in range(1, MAX_BLOCKS + 1):
            perm = modem.interleaver(blocks, n)
            off, _ = blob.put(perm.astype("<i4"), "<i4")
            perms.append(off)
        rungs.append(
            {
                "name": m.label,
                "index": i,
                "bps": int(m.bps),
                "rep": int(m.rep),
                "block_mult": int(m.block_mult),
                "uncoded": int(bool(m.uncoded)),
                "n": int(n),
                "k": int(k),
                "edge_off": int(edge_off),
                "edges": int(edges // 2),
                "perm_off": perms,
            }
        )

    info = {
        "fs": phy.fs,
        "n_fft": phy.n_fft,
        "cp": phy.cp,
        "bin_lo": int(phy.bin_lo),
        "bin_hi": int(phy.bin_hi),
        "pilot_step": phy.pilot_step,
        "preamble_syms": phy.preamble_syms,
        "header_syms": phy.header_syms,
        "syms_per_block": phy.syms_per_block,
        "sym_len": phy.sym_len,
        "n_data": int(phy.n_data),
        "n_pilots": int(phy.n_pilots),
        "header_n": modem.header_n,
        "header_k": modem.header_k,
        "preamble_off": int(pre_off),
        "preamble_len": int(pre_len),
        "pilot_off": int(pilot_off),
        "header_edge_off": int(hdr_edge_off),
        "header_edges": int(hdr_edges // 2),
        "rungs": rungs,
    }

    bin_path = os.path.join(DATA, "wide.bin")
    with open(bin_path, "wb") as fh:
        fh.write(blob.buf)
    print(f"wrote {bin_path}: {len(blob.buf) / 1e6:.2f} MB, {len(rungs)} rungs")

    emit_header(blob, info)

    # Golden waveforms: the Python transmitter's own output, for the C++ receiver.
    payload = b"test de halcyon k"
    for idx in (0, 4, 9, 16):
        wave, blocks = modem.build(payload, idx)
        w = np.asarray(wave, np.complex64)
        flat = np.stack([w.real, w.imag], axis=1).astype("<f4").ravel()
        path = os.path.join(VEC, f"py_mcs{idx:02d}.f32")
        flat.tofile(path)
        res = modem.receive(np.asarray(wave, np.complex128) + 0.0)
        print(
            f"  py mcs {idx:2d} {table_for(phy)[idx].label:<14} "
            f"{w.size / phy.fs:.2f} s, {blocks} block(s) -> "
            f"{res.payload.decode('ascii', 'replace')!r} snr {res.snr_db:+.1f}"
        )
    with open(os.path.join(VEC, "expected.txt"), "w", encoding="utf-8") as fh:
        fh.write(payload.decode())


if __name__ == "__main__":
    main()
